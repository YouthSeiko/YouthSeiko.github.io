"""Build the browser catalogue from [French, English, Japanese] entries. No deps."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if the generated JS is stale')
args = parser.parse_args()
rows = json.loads((ROOT / 'assets/i18n/catalogue.json').read_text(encoding='utf-8'))
catalogue = {}
for row in rows:
    if len(row) != 3 or not all(isinstance(value, str) for value in row):
        raise ValueError('Each entry must contain three strings')
    key = re.sub(r'\s+', ' ', row[0]).strip()
    if key in catalogue:
        raise ValueError(f'Duplicate source: {key}')
    catalogue[key] = row[1:]
output = '// Generated by tools/build_i18n.py. Edit assets/i18n/catalogue.json.\n'
output += 'window.YOUTHSEIKO_I18N = ' + json.dumps(catalogue, ensure_ascii=False, indent=2) + ';\n'
target = ROOT / 'assets/js/i18n-catalogue.js'
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        raise SystemExit('The browser catalogue needs regeneration')
else:
    target.write_text(output, encoding='utf-8', newline='\n')
print(f'{len(catalogue)} entries; browser catalogue is current')
