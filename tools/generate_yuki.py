"""Local VOICEVOX -> small MP3 files and a static bilingual browser catalogue.
No Python, synthesis engine or external voice API is needed by site visitors.
"""
import argparse
import hashlib
import json
import subprocess
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--engine', default='http://127.0.0.1:50021')
    args = parser.parse_args()
    if urllib.parse.urlparse(args.engine).hostname not in ('127.0.0.1', 'localhost'):
        raise SystemExit('Use a local VOICEVOX engine only.')
    config = json.loads((ROOT / 'tools/yuki-lines.json').read_text(encoding='utf-8'))
    out = ROOT / 'assets/voice/yuki'
    raw_dir = ROOT.parent / 'yuki-voice-source-v1'
    out.mkdir(parents=True, exist_ok=True)
    raw_dir.mkdir(parents=True, exist_ok=True)

    def request(endpoint, params=None, data=None):
        url = args.engine + endpoint
        if params:
            url += '?' + urllib.parse.urlencode(params)
        req = urllib.request.Request(url, data=data, headers={'Content-Type': 'application/json'})
        with urllib.request.urlopen(req, timeout=180) as res:
            return res.read()

    speakers = json.loads(request('/speakers'))
    speaker = next(s for s in speakers if s['name'] == config['speaker'])
    style = next(s for s in speaker['styles'] if s['name'] == config['style'])
    metadata_file = out / 'generation.json'
    old = json.loads(metadata_file.read_text(encoding='utf-8')) if metadata_file.exists() else {}
    version = json.loads(request('/version'))
    metadata = {'engine': version, 'credit': config['credit'], 'speaker_id': style['id'], 'files': {}}
    catalogue = []
    for line in config['lines']:
        clip = out / (line['id'] + '.mp3')
        settings = dict(config['settings'], **line.get('settings', {}))
        fingerprint = hashlib.sha256(json.dumps([version, style['id'], line['japanese'], settings], ensure_ascii=False).encode()).hexdigest()
        cached = old.get('files', {}).get(line['id'], {})
        if not (clip.exists() and cached.get('input_sha256') == fingerprint
                and cached.get('sha256') == hashlib.sha256(clip.read_bytes()).hexdigest()):
            query = json.loads(request('/audio_query', {'text': line['japanese'], 'speaker': style['id']}, b''))
            query.update(settings)
            query.update(volumeScale=1.0, prePhonemeLength=0.06, postPhonemeLength=0.15,
                         outputSamplingRate=24000, outputStereo=False)
            raw = raw_dir / (line['id'] + '.wav')
            (raw_dir / (line['id'] + '-query.json')).write_text(json.dumps(query, ensure_ascii=False, indent=2), encoding='utf-8')
            raw.write_bytes(request('/synthesis', {'speaker': style['id'], 'enable_interrogative_upspeak': 'true'},
                                    json.dumps(query, ensure_ascii=False).encode('utf-8')))
            subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(raw),
                            '-af', 'loudnorm=I=-19:TP=-3:LRA=7', '-ar', '24000', '-ac', '1',
                            '-codec:a', 'libmp3lame', '-b:a', '64k', '-map_metadata', '-1', str(clip)], check=True)
            print('Generated: ' + line['id'], flush=True)
        else:
            print('Preserved: ' + line['id'], flush=True)
        digest = hashlib.sha256(clip.read_bytes()).hexdigest()
        metadata['files'][line['id']] = {'input_sha256': fingerprint, 'sha256': digest, 'bytes': clip.stat().st_size}
        catalogue.append({'id': line['id'], 'french': line['french'], 'japanese': line['japanese'],
                          'audio': 'assets/voice/yuki/' + clip.name + '?v=' + digest[:12]})
        # Checkpoint successful files so interrupted generation can resume.
        metadata_file.write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding='utf-8')
    (ROOT / 'assets/js/yuki-lines.js').write_text('// Generated by tools/generate_yuki.py\nwindow.YUKI_LINES = ' +
                                               json.dumps(catalogue, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f'Ready: {len(catalogue)} Japanese MP3s with French subtitles', flush=True)


if __name__ == '__main__':
    main()
